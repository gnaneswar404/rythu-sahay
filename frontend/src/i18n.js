export function translateText(language, value) {
  if (typeof value !== 'string') return value
  if (language !== 'en') {
    return teluguApiErrors[value] || value
  }
  const trimmed = value.trim()
  const translated = english[trimmed]
  const caseRegistration = trimmed.match(/^ధన్యవాదాలు\. మీ అభ్యర్థన (.+)గా నమోదు చేశాము\. తదుపరి సలహా కోసం స్థానిక వ్యవసాయ అధికారిని సంప్రదించండి\. ధృవీకరించిన మార్గదర్శకం లేకుండా మందులు వాడవద్దు\.$/)
  const message = translated || (caseRegistration
    ? `Thank you. Your request ${caseRegistration[1]} has been registered. Contact a local agricultural officer for further advice. Do not use any medicine without verified guidance.`
    : null)
  if (!message) return value
  const leading = value.slice(0, value.indexOf(trimmed))
  const trailing = value.slice(value.indexOf(trimmed) + trimmed.length)
  return `${leading}${message}${trailing}`
}

function translateNode(language, node) {
  if (typeof node === 'string') return translateText(language, node)
  if (!isValidElement(node)) return node

  const props = {}
  for (const attribute of ['aria-label', 'alt', 'placeholder', 'title']) {
    if (typeof node.props[attribute] === 'string') {
      props[attribute] = translateText(language, node.props[attribute])
    }
  }
  const children = Children.map(node.props.children, (child) => translateNode(language, child))
  return cloneElement(node, props, children)
}

export function translateTree(language, children) {
  return Children.map(children, (child) => translateNode(language, child))
}
